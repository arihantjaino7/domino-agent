"""Render evaluation markdown from recorded JSON only; no database or model access."""

from __future__ import annotations

import argparse
import json
import math
from collections import defaultdict
from pathlib import Path


def percentile(values: list[float], p: float) -> float | None:
    if not values:
        return None
    return sorted(values)[max(0, math.ceil(p * len(values)) - 1)]


def money(cents: int) -> str:
    sign = "-" if cents < 0 else ""
    cents = abs(cents)
    return f"{sign}${cents // 100:,}.{cents % 100:02d}"


def ratio(num: int, den: int) -> str:
    return f"{num}/{den}" if den else "N/A (empty denominator)"


def render(data: dict) -> str:
    rows = data["cases"]
    generated = [r for r in rows if r["seed"] is not None]
    base = [r for r in rows if r["method"] == "B0"]
    output = ["# Evaluation results", "", "Generated by `uv run --project backend python -m eval.run`; do not edit numbers by hand.", "",
              f"Status: **{'PASS' if not data['failures'] else 'INCOMPLETE / FAIL — inspect the failures below'}**. "
              f"Recorded evaluation failures: **{len(data['failures'])}**.", "",
              "## Reproduce", "", "```powershell", "uv sync --project backend", "uv run --project backend pytest eval -q",
              f"uv run --project backend python -m eval.run --seed-start {data['seeds'][0]} --seed-count {len(data['seeds'])} --scripted-repeats {data.get('scripted_repeats', 2)}",
              "```", "", "`make eval` runs the default evaluation. FalkorDB must be running. No paid API is called. "
              "Base/world/memory writes use unique `eval:*` graphs; scripted tools also use their own temporary sandbox/flow graphs, removed by the engines. "
              "Live worlds and normal memory are not used for evaluation.", "",
              "Raw metrics, plans, receipts, failures and query samples are in [results.json](results.json). "
              "Raw world JSON exports are saved under `eval/out/` (ignored by Git); their hashes and generator fingerprints are recorded in the metrics. "
              "Regenerate Markdown without rerunning engines with `uv run --project backend python -m eval.report`.", "",
              "## Protocol and boundaries", "",
              f"- Fixed consecutive seeds: `{data['seeds']}`; each receives Monsoon and Panel Fire. "
              "Seeds are selected before scoring, without filtering for better outcomes.",
              f"- Horizon ends on day {data['horizon_days']} (day 0 through the end day, inclusive); budget: {money(data['budget_cents'])} per decision.",
              "- B0: do nothing. B1 and B2 share the production greedy allocator, cheapest-first ranking, budget, sea shipping and orders. "
              "B1 uses nominal tier-1 capacity; B2 adds clean-capacity and shared-upstream checks (S1 versus S2). "
              "Both receive the same graph-derived late-order list; this comparison isolates recovery allocation/capacity checks, not end-to-end detection. Their difference measures upstream visibility in allocation, not graph database superiority over SQL.",
              "- S4 is shown separately: it also changes ranking and allows air when needed. Its gains cannot be attributed only to graph visibility.",
              "- All methods are scored by the same deterministic sandbox reality model. Recovery is protected (projected); no physical arrival is claimed.",
              "- The oracle reads raw exported nodes and edges and imports no production engines. NetworkX computes traversal, ordering and max-flow. "
              "A separate exact-fraction inventory ledger checks each order’s ready day, lateness, penalties and PO realized rates.",
              "- The oracle checks the documented bounded traversal, pipeline timing, single-commodity flow bound and one-tier PO rationing model. "
              "Agreement is not independent validation of those modelling assumptions. Complementary inputs are checked explicitly in shortage tests; max-flow remains an upper bound.",
              "- B1 verifier violations and zero-clean-source selections are diagnostic outcomes, not hidden or counted as harness failures. "
              "Oracle mismatches, exceptions, graph-aware safety failures and scripted smoke failures make the command exit nonzero.",
              "- D/CP-SAT is not implemented and is not reported. A/real-model agency is **not measured**: API/Claude subscription runs are not performed here. "
              "P-scripted is labelled as a plumbing test, not proof of intelligent tool selection, ambiguity handling or replanning.", "",
              "## Generated-world recovery totals", "",
              "Totals below sum all completed generated scenario cases, not unique orders in the original world. "
              "Each seed’s two incident scenarios are separate trials. Adversarial fixtures are excluded from these totals.", "",
              "| Method | Completed cases | On time / orders | Late | Spend | Penalty | Failed verifier checks | Trap findings |",
              "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for method in ["B0", "B1", "B2", "S4"]:
        selected = [r for r in generated if r["method"] == method]
        if not selected:
            output.append(f"| {method} | 0 | N/A | N/A | N/A | N/A | N/A | N/A |")
            continue
        sums = {k: sum(r["score"][k] for r in selected) for k in ["on_time", "orders", "late", "spend_cents", "penalty_cents"]}
        failed = sum(len(r["verification"]["failed"]) for r in selected if r["verification"])
        bad = sum(len(r["traps"]) for r in selected)
        output.append(f"| {method} | {len(selected)} | {sums['on_time']}/{sums['orders']} | {sums['late']} | "
                      f"{money(sums['spend_cents'])} | {money(sums['penalty_cents'])} | {failed if method != 'B0' else 'N/A'} | {bad} |")
    if not generated:
        output += ["", "**No database recovery scores were collected.** See [database-free projection checks](OFFLINE_CHECKS.md) and [read-only snapshot checks](READ_ONLY_CHECKS.md) for the narrower checks that could run."]
    output += ["", "Trap-free trials (zero-clean-capacity and incompatible sources; partial exposure alone is allowed):"]
    for method in ["B1", "B2", "S4"]:
        selected = [r for r in generated if r["method"] == method]
        output.append(f"- {method}: {ratio(sum(not r['traps'] for r in selected), len(selected))}.")
    pairs = defaultdict(dict)
    for r in generated:
        pairs[r["case"]][r["method"]] = r
    complete = [p for p in pairs.values() if {"B1", "B2"} <= p.keys()]
    deltas = [p["B1"]["score"]["late"] - p["B2"]["score"]["late"] for p in complete]
    output += ["", f"Paired B2 versus B1: {len(complete)} pairs; B2 has fewer late orders in {sum(d > 0 for d in deltas)}, "
               f"ties in {sum(d == 0 for d in deltas)}, and more late orders in {sum(d < 0 for d in deltas)}. "
               f"Total late-order reduction: {sum(deltas)}.", "",
               "## Per-scenario results (all generated seeds)", "",
               "| Scenario | Method | Cases | Late | Spend | Protected but still late |", "|---|---|---:|---:|---:|---:|"]
    for scenario in ["monsoon", "panel_fire"]:
        for method in ["B0", "B1", "B2", "S4"]:
            selected = [r for r in generated if r["scenario"] == scenario and r["method"] == method]
            if not selected:
                output.append(f"| {scenario} | {method} | 0 | N/A | N/A | N/A |")
                continue
            output.append(f"| {scenario} | {method} | {len(selected)} | {sum(r['score']['late'] for r in selected)} | "
                          f"{money(sum(r['score']['spend_cents'] for r in selected))} | "
                          f"{sum(len(r['score']['protected_but_late']) for r in selected)} |")
    output += ["", "## Demo seed results", "", "| Seed | Scenario | Method | On time / orders | Late | Spend | Verifier failures |",
               "|---:|---|---|---:|---:|---:|---|"]
    for r in generated:
        if r["seed"] != data["seeds"][0]:
            continue
        failed = ", ".join(r["verification"]["failed"]) or "none" if r["verification"] else "N/A"
        output.append(f"| {r['seed']} | {r['scenario']} | {r['method']} | {r['score']['on_time']}/{r['score']['orders']} | "
                      f"{r['score']['late']} | {money(r['score']['spend_cents'])} | {failed} |")
    output += ["", "## Oracle and evidence agreement", "",
               f"Healthy-world baseline: {sum(x['ok'] for x in data['healthy'])}/{len(data['healthy'])} worlds "
               "have zero projected-late orders and match the oracle.", "",
               "Classification uses micro totals across baseline cases. Precision = TP/(TP+FP), recall = TP/(TP+FN). "
               "Empty denominators are N/A. True negatives do not inflate these metrics.", "",
               "| Check | Precision | Recall | False positives | False negatives |", "|---|---:|---:|---:|---:|"]
    for label, key in [("Exposed orders", "exposure"), ("Projected-late orders", "late_classification")]:
        tp, fp, fn = [sum(r[key][k] for r in base) for k in ["tp", "fp", "fn"]]
        output.append(f"| {label} | {ratio(tp, tp + fp)} | {ratio(tp, tp + fn)} | {fp} | {fn} |")
    capacity = [c for r in base for c in r["capacity_checks"]]
    output += ["", f"Evidence paths structurally valid: {sum(r['evidence']['valid'] for r in base)}/{sum(r['evidence']['total'] for r in base)}. "
               "This checks origin, FEEDS hops, supply contract, plant/product and required component/order joins.", "",
               f"NetworkX max-flow and per-source capacities agree: {sum(c['matches'] for c in capacity)}/{len(capacity)} component/plant checks. "
               f"Projection comparisons with per-order readiness/penalty/rate mismatches: {sum(bool(r['oracle_differences']) for r in rows)}/{len(rows)}.", "",
               "## Adversarial fixtures", "", "| Fixture | Method | Late | Verifier failures | Oracle mismatches |",
               "|---|---|---:|---|---:|"]
    for r in rows:
        if r["seed"] is not None:
            continue
        failed = ", ".join(r["verification"]["failed"]) or "none" if r["verification"] else "N/A"
        output.append(f"| {r['case']} | {r['method']} | {r['score']['late']} | {failed} | {len(r['oracle_differences'])} |")
    output += ["", "Hand-worked assertions in `eval/test_oracle.py` cover pipeline timing, shared lines, complementary inputs, "
               "partial exposure, day-zero/horizon behavior, cycle rejection and exact joint rationing. "
               "`eval/fixtures.py` records expected ready days rather than deriving them from the engine.", "",
               "## Free scripted MCP plumbing (P-scripted)", "",
               "Synthetic approvals below apply only to evaluation graphs. No human approval or paid-model intelligence is inferred.", "",
               "| Scenario | Repeat | Status | Outcome | Tool calls | Paused for approval | API cost |",
               "|---|---:|---|---|---:|---|---:|"]
    for r in data["scripted"]:
        output.append(f"| {r['scenario']} | {r['repeat']} | {'PASS' if r['ok'] else 'FAIL'} | {r['outcome']} | {r['tool_calls']} | "
                      f"{r['waited_for_approval']} | ${r['cost_usd']:.4f} |")
    output += ["", "Non-event checks require `not_in_graph`, no approval pause and an unchanged world. "
               "Disruption runs require no POs before approval and passing verification afterwards. "
               "Numeric faithfulness of free-form real-model narratives, real-model tool-path diversity, ambiguous-alert clarification "
               "and second-disruption replanning remain unmeasured.", "",
               "## Runtime", "",
               "| Method | Samples | p50 ms | p95 ms |", "|---|---:|---:|---:|"]
    for method in ["B0", "B1", "B2", "S4"]:
        values = [r["runtime_ms"] for r in generated if r["method"] == method]
        if values:
            output.append(f"| {method} | {len(values)} | {percentile(values, .5):.2f} | {percentile(values, .95):.2f} |")
    setup = [r["common_problem_setup_ms"] for r in generated if r["method"] == "B1"]
    if setup:
        output += ["", f"Shared problem construction (once per case): p50 {percentile(setup, .5):.2f} ms; "
                   f"p95 {percentile(setup, .95):.2f} ms. B0 times projection only; recovery times include allocation, "
                   "proposal, approval, execution, projection and verification, excluding graph copy, raw export and oracle calculation. "
                   "These scopes differ; this is not a claim that method runtime ratios measure only allocation speed."]
    output += ["", "## Named query performance", "",
               "Nearest-rank p50/p95 of successful `run_query` calls as logged (0.01 ms resolution). "
               "Includes reads, writes and scratch-graph queries; excludes GRAPH.COPY/deletion, Python work and failed queries. "
               "Setup, healthy checks and scripted plumbing are separated from scored evaluation. "
               "Local measurements include cold/warm effects and must not be presented as deployment latency.", "",
               "| Phase | Query | Calls | p50 ms | p95 ms |", "|---|---|---:|---:|---:|"]
    for phase, queries in sorted(data["query_samples_ms"].items()):
        for name, values in sorted(queries.items()):
            output.append(f"| {phase} | `{name}` | {len(values)} | {percentile(values, .5):.2f} | {percentile(values, .95):.2f} |")
    output += ["", "## Environment history", "",
               "See [ENVIRONMENT.md](ENVIRONMENT.md) for the initial Docker I/O failure, approved restart attempt and graph backups. "
               "A successful future rerun replaces the main scores; it does not erase this incident record."]
    output += ["", "## Failures", ""]
    if data["failures"]:
        for failure in data["failures"]:
            output.append(f"- **{failure['case']} — {failure['kind']}**: {json.dumps(failure['details'], ensure_ascii=False)[:700]}")
    else:
        output.append("No oracle, harness, graph-aware safety or scripted smoke failures were recorded. "
                      "Baseline verifier failures remain visible above and in the raw rows.")
    output += ["", "## Provenance", "", f"Generated (UTC): {data['generated_utc']}.", "",
               f"Source Git HEAD before run: `{data['provenance']['git_head']}`. "
               f"Source digest: `{data['provenance']['source_sha256']}`.", "",
               f"Python {data['provenance']['python']}; NetworkX {data['provenance']['networkx']}; "
               f"FalkorDB graph module {data['provenance']['graph_module_ver']}; {data['provenance']['platform']}.", "",
               f"Total run elapsed: {data['elapsed_seconds']:.2f} seconds. Source digest covers checked-in and working-tree "
               "Python/Cypher under backend/domino, eval and scripts at run time. Exact runtime values can vary; "
               "deterministic outcome fields should reproduce."]
    return "\n".join(output) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=Path(__file__).with_name("results.json"))
    args = parser.parse_args()
    data = json.loads(args.input.read_text(encoding="utf-8"))
    args.input.with_name("RESULTS.md").write_text(render(data), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
