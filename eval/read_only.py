"""Read-only conformance checks on existing worlds; never recovery benchmark scores."""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

from domino.engines.exposure import trace_exposure
from domino.engines.shortage import project_shortages
from domino.graph.run_query import capture_queries
from eval.oracle import World
from eval.run import bound_connection, classification, compare_projection
from eval.report import percentile
from scripts.export_world_json import export_world


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--render-only", action="store_true", help="Regenerate Markdown from saved JSON without database access")
    args = parser.parse_args()
    if args.render_only:
        output = Path(__file__).parent
        saved = json.loads((output / "read_only_results.json").read_text(encoding="utf-8"))
        write_report(saved, output)
        return
    bound_connection()
    graphs = ["world:pristine", "world:live", "world:cli:monsoon", "world:cli:panel_fire"]
    rows = []
    for graph in graphs:
        try:
            with capture_queries() as records:
                data = export_world(graph)
                oracle = World(data)
                projection = project_shortages(graph)
                differences = compare_projection(projection, oracle.project())
                evidence = []
                for node in data["nodes"]:
                    if "Incident" not in node["labels"]:
                        continue
                    incident = node["props"]["id"]
                    affected = [e["dst"] for e in data["edges"] if e["type"] == "AFFECTS" and e["src"] == incident]
                    trace = trace_exposure(graph, incident)
                    agreement = classification(set(trace["order_evidence"]), oracle.exposure(affected))
                    paths = oracle.validate_evidence(trace, affected)
                    evidence.append({"incident": incident, "agreement": agreement, "paths": paths})
                after = export_world(graph)
            unchanged = data == after
            ok = unchanged and not differences and all(not e["agreement"]["fp"] and not e["agreement"]["fn"]
                                                        and not e["paths"]["invalid"] for e in evidence)
            rows.append({"graph": graph, "ok": ok, "unchanged": unchanged, "oracle_differences": differences,
                         "totals": projection["totals"], "evidence": evidence,
                         "query_samples_ms": [{"name": r.name, "ms": r.ms, "ro": r.ro} for r in records]})
            assert all(r.ro for r in records), "Read-only probe attempted a write"
        except Exception as exc:
            rows.append({"graph": graph, "ok": False, "error_type": type(exc).__name__, "error": str(exc)})
    output = Path(__file__).parent
    data = {"generated_utc": datetime.now(timezone.utc).isoformat(),
            "scope": "read-only checks of existing demo snapshots; not generated recovery trials", "checks": rows}
    (output / "read_only_results.json").write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    write_report(data, output)
    print(f"Read-only snapshot checks: {sum(r['ok'] for r in rows)}/{len(rows)} pass")
    raise SystemExit(1 if any(not r["ok"] for r in rows) else 0)


def write_report(data: dict, output: Path) -> None:
    rows = data["checks"]
    text = ["# Read-only graph conformance checks", "", "Generated by `uv run --project backend python -m eval.read_only`.", "",
            f"Result: **{sum(r['ok'] for r in rows)}/{len(rows)} snapshots pass**.", "",
            "These are existing demo snapshots, not newly generated independent trials. All recorded queries use GRAPH.RO_QUERY. "
            "Before/after raw exports must be identical. The checks compare query-backed production projections with the JSON oracle, "
            "including committed-PO realized rates, per-order readiness and penalties. Existing incident exposure and evidence are checked too.", "",
            "No graph is copied, seeded, reset or modified. These checks do not establish B1/B2 recovery comparisons or database max-flow accuracy.", "",
            "| Existing graph | Projection/evidence match | Unchanged |", "|---|---|---|"]
    for row in rows:
        text.append(f"| `{row['graph']}` | {'PASS' if row['ok'] else 'FAIL'} | {row.get('unchanged', 'N/A')} |")
    text += ["", "Full results: [read_only_results.json](read_only_results.json). Main evaluation: [RESULTS.md](RESULTS.md)."]
    text += ["", f"Recorded (UTC): {data['generated_utc']}.", "", "## Observed read-only query timings", "",
             "These few samples come from the four existing snapshots above, not the planned generated-world benchmark. "
             "Nearest-rank p50/p95 use the runner’s 0.01 ms log resolution; they exclude Python work and failed queries.", "",
             "| Query | Calls | p50 ms | p95 ms |", "|---|---:|---:|---:|"]
    samples = defaultdict(list)
    for row in rows:
        for query in row.get("query_samples_ms", []):
            samples[query["name"]].append(query["ms"])
    for name, values in sorted(samples.items()):
        text.append(f"| `{name}` | {len(values)} | {percentile(values, .5):.2f} | {percentile(values, .95):.2f} |")
    (output / "READ_ONLY_CHECKS.md").write_text("\n".join(text) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
