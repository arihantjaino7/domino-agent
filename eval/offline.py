"""Database-free projection regression checks. These are not sandbox recovery scores.

A raw seed snapshot is adapted to the public pure `shortage.project` input schema.
Cypher extraction, FalkorDB max-flow, executor and recovery allocation are NOT tested.
"""

from __future__ import annotations

import copy
import json
from collections import defaultdict
from pathlib import Path

from domino.engines.shortage import project
from domino.seed.generator import generate
from eval.fixtures import snapshot
from eval.oracle import World
from eval.run import compare_projection


def inputs_from_snapshot(data: dict, horizon: int = 42) -> dict:
    nodes = {row["props"]["id"]: row["props"] for row in data["nodes"]}
    rels = defaultdict(list)
    for edge in data["edges"]:
        rels[edge["type"]].append(edge)
    by_source = lambda rel: {e["src"]: e["dst"] for e in rels[rel]}
    products, plants = by_source("FOR_PRODUCT"), by_source("FULFILLED_AT")
    customers = {e["dst"]: e["src"] for e in rels["PLACED"]}
    order_rows = []
    for oid, product in products.items():
        o, c = nodes[oid], nodes[customers[oid]]
        if o["status"] not in {"open", "protected_projected"} or o["need_day"] > horizon:
            continue
        for required in rels["REQUIRES"]:
            if required["src"] == product:
                order_rows.append({"order_id": oid, "plant": plants[oid], "product": product,
                                   "need_day": o["need_day"], "qty": o["qty"], "customer": customers[oid],
                                   "tier": c["tier"], "penalty_cents": c["penalty_per_day_cents"],
                                   "value_cents": o["value_cents"], "component": required["dst"],
                                   "units": o["qty"] * required["props"]["qty"]})
    return {"horizon": horizon, "pos": [], "order_rows": order_rows,
            "sites": {r["props"]["id"]: {"factor": r["props"].get("capacity_factor", 1),
                      "disrupted_until": r["props"].get("disrupted_until"),
                      "input_buffer_days": r["props"].get("input_buffer_days", 0)}
                      for r in data["nodes"] if "Site" in r["labels"]},
            "feeds": [{"src": e["src"], "dst": e["dst"], "component": e["props"]["component_id"],
                       "used_wk": e["props"]["used_wk"], "cap_wk": e["props"]["cap_wk"]} for e in rels["FEEDS"]],
            "supply": [{"site": e["src"], "plant": e["dst"], "component": e["props"]["component_id"],
                        "used_wk": e["props"]["used_wk"], "transit_days": e["props"]["transit_days"]}
                       for e in rels["SUPPLIES"]],
            "stock": [{"plant": e["src"], "component": e["dst"], "on_hand": e["props"]["on_hand"]}
                      for e in rels["STOCKS"]]}


def check_seed(seed: int) -> list[dict]:
    pristine = snapshot(generate(seed))
    checks = []
    # Explicit fixture footprints, separate from the oracle's entity expansion.
    for scenario, site, duration in [("healthy", None, 0), ("monsoon", "S-VOLT-AYU", 28),
                                     ("panel_fire", "S-LMVU-SUZ", 14)]:
        actual_data = copy.deepcopy(pristine)
        for row in actual_data["nodes"]:
            if row["props"]["id"] == site:
                row["props"].update(capacity_factor=0.0, disrupted_until=duration, status="disrupted")
        independent = World(pristine).disrupted([site], 0, duration) if site else World(pristine)
        actual = project(inputs_from_snapshot(actual_data))
        expected = independent.project()
        differences = compare_projection(actual, expected)
        if scenario == "healthy" and actual["totals"]["projected_late"]:
            differences.append({"field": "healthy_projected_late", "actual": actual["totals"]["projected_late"], "expected": 0})
        checks.append({"seed": seed, "scenario": scenario, "ok": not differences,
                       "orders": actual["totals"]["orders"], "projected_late": actual["totals"]["projected_late"],
                       "penalty_cents": actual["totals"]["penalty_exposure_cents"], "differences": differences})
    return checks


def main() -> None:
    checks = []
    for seed in range(42, 62):
        checks.extend(check_seed(seed))
        print(f"Offline projection seed {seed}", flush=True)
    output = Path(__file__).parent
    data = {"scope": "pure shortage projection only; no database or recovery scores", "seeds": list(range(42, 62)), "checks": checks}
    (output / "offline_results.json").write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    failed = [r for r in checks if not r["ok"]]
    text = ["# Database-free projection checks", "", "Generated by `uv run --project backend python -m eval.offline`.", "",
            f"Result: **{len(checks) - len(failed)}/{len(checks)} checks pass** across seeds 42–61.", "",
            "These checks compare the production pure shortage function with the independent JSON oracle for healthy, Monsoon and Panel Fire inputs. "
            "They verify per-order ready days and total penalties. Healthy worlds must also have zero late orders. "
            "Incident footprints are explicit fixture inputs, not tested Cypher resolution.", "",
            "This does **not** validate graph extraction, database max-flow, sandbox copies, the executor, B1/B2 recovery comparisons or real-model agency. "
            "See [RESULTS.md](RESULTS.md) for the database evaluation status and [offline_results.json](offline_results.json) for every result.", "",
            "| Scenario | Checks | Pass | Fail |", "|---|---:|---:|---:|"]
    for scenario in ["healthy", "monsoon", "panel_fire"]:
        selected = [r for r in checks if r["scenario"] == scenario]
        text.append(f"| {scenario} | {len(selected)} | {sum(r['ok'] for r in selected)} | {sum(not r['ok'] for r in selected)} |")
    if failed:
        text += ["", "## Failures", "", "```json", json.dumps(failed, indent=2), "```"]
    (output / "OFFLINE_CHECKS.md").write_text("\n".join(text) + "\n", encoding="utf-8", newline="\n")
    raise SystemExit(1 if failed else 0)


if __name__ == "__main__":
    main()
