"""Regenerate docs/QUERIES.md from the checked-in Cypher files (standard library only)."""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend" / "domino"
QUERIES = BACKEND / "queries"
OUTPUT = ROOT / "docs" / "QUERIES.md"


def anchor(name: str) -> str:
    return re.sub(r"[^\w-]", "", name.lower())


def generate() -> str:
    sources = [(p.relative_to(ROOT).as_posix(), p.read_text(encoding="utf-8"))
               for p in sorted(BACKEND.rglob("*.py"))]
    groups: dict[str, list[tuple[str, str, str, list[str]]]] = defaultdict(list)
    for path in sorted(QUERIES.rglob("*.cypher"),
                       key=lambda p: (p.parent.relative_to(QUERIES).as_posix(), p.name)):
        name = path.relative_to(QUERIES).with_suffix("").as_posix()
        lines = path.read_text(encoding="utf-8").splitlines()
        description = []
        while lines and lines[0].startswith("//"):
            description.append(lines.pop(0)[2:].strip())
        references = [file for file, source in sources
                      if f'"{name}"' in source or f"'{name}'" in source]
        folder = path.parent.relative_to(QUERIES).as_posix()
        groups[folder].append((name, " ".join(description), "\n".join(lines).strip(), references))

    folders = sorted(groups, key=lambda f: (f.split("/")[0] in {"seed", "schema"}, f))
    out = ["# Cypher query reference", "",
           "Generated by `scripts/gen_queries_md.py`; do not edit this file by hand.", "",
           "## Contents", ""]
    for folder in folders:
        out.append(f"- {folder}")
        out.extend(f"  - [{name}](#{anchor(name)})" for name, *_ in groups[folder])
    setup_started = False
    for folder in folders:
        if folder.split("/")[0] in {"seed", "schema"}:
            if not setup_started:
                out.extend(["", "## Setup and seeding queries"])
                setup_started = True
        else:
            out.extend(["", f"## {folder}"])
        for name, description, query, references in groups[folder]:
            used = ", ".join(f"`{file}`" for file in references) or "not referenced in code"
            out.extend(["", f"### {name}", "", description or "No leading description.", "",
                        f"Used by: {used}", "", "```cypher", query, "```"])
    return "\n".join(out) + "\n"


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generate(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
